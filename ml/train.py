"""Train the GGTF ML symbol decoder.

Reads features generated by `cargo run --release -p ggtf-core --example ml_data`,
trains a small MLP (112 -> 128 -> 96 -> 16), compares it with the classic decoder on the
validation set, and writes:
  crates/ggtf-core/models/symbol_mlp.bin   weights in the format read by ml.rs (embedded in WASM)
  ml/models/symbol_mlp.onnx                the same network as ONNX, for inspection / other runtimes
  ml/models/report.json                    accuracies

Usage: python ml/train.py [--epochs 12] [--data ml/data]
"""

import argparse
import json
import struct
import time
from pathlib import Path

import numpy as np
import torch
from torch import nn

N_FEATURES = 112
TONES = 16
ROOT = Path(__file__).resolve().parent.parent


def load(split_dir: Path):
    x = np.fromfile(split_dir / "x.f32", dtype="<f4").reshape(-1, N_FEATURES)
    y = np.fromfile(split_dir / "y.u8", dtype=np.uint8).astype(np.int64)
    assert len(x) == len(y), "feature/label count mismatch"
    return x, y


def build():
    return nn.Sequential(nn.Linear(N_FEATURES, 128), nn.ReLU(), nn.Linear(128, 96), nn.ReLU(), nn.Linear(96, TONES))


def export_bin(model: nn.Sequential, path: Path):
    linears = [m for m in model if isinstance(m, nn.Linear)]
    with open(path, "wb") as f:
        f.write(b"GGTF")
        f.write(struct.pack("<I", len(linears)))
        for lin in linears:
            w = lin.weight.detach().cpu().numpy().astype("<f4")  # [out, in], row-major
            b = lin.bias.detach().cpu().numpy().astype("<f4")
            f.write(struct.pack("<II", w.shape[1], w.shape[0]))
            f.write(w.tobytes())
            f.write(b.tobytes())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "ml" / "data"))
    ap.add_argument("--epochs", type=int, default=12)
    ap.add_argument("--batch", type=int, default=2048)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    xtr, ytr = load(Path(args.data) / "train")
    xva, yva = load(Path(args.data) / "val")
    print(f"train {len(ytr):,} symbols, val {len(yva):,} symbols")

    # Classic decoder = loudest tone in the full window = argmax of the first 16 features.
    classic_val = float((xva[:, :TONES].argmax(1) == yva).mean())
    print(f"classic decoder symbol accuracy on val: {classic_val:.4f}")

    dev = "cuda" if torch.cuda.is_available() else "cpu"
    model = build().to(dev)
    opt = torch.optim.AdamW(model.parameters(), lr=2e-3, weight_decay=1e-4)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.epochs)
    loss_fn = nn.CrossEntropyLoss()
    xt, yt = torch.from_numpy(xtr).to(dev), torch.from_numpy(ytr).to(dev)
    xv, yv = torch.from_numpy(xva).to(dev), torch.from_numpy(yva).to(dev)

    best, best_state = 0.0, None
    t0 = time.time()
    for ep in range(args.epochs):
        model.train()
        perm = torch.randperm(len(yt), device=dev)
        total = 0.0
        for i in range(0, len(perm), args.batch):
            idx = perm[i : i + args.batch]
            opt.zero_grad()
            loss = loss_fn(model(xt[idx]), yt[idx])
            loss.backward()
            opt.step()
            total += loss.item() * len(idx)
        sched.step()
        model.eval()
        with torch.no_grad():
            acc = (model(xv).argmax(1) == yv).float().mean().item()
        print(f"epoch {ep + 1:2d}  loss {total / len(yt):.4f}  val acc {acc:.4f}  ({time.time() - t0:.0f} s)")
        if acc > best:
            best, best_state = acc, {k: v.detach().clone() for k, v in model.state_dict().items()}

    model.load_state_dict(best_state)
    model = model.cpu().eval()
    out_bin = ROOT / "crates" / "ggtf-core" / "models" / "symbol_mlp.bin"
    export_bin(model, out_bin)
    models_dir = ROOT / "ml" / "models"
    models_dir.mkdir(parents=True, exist_ok=True)
    try:
        torch.onnx.export(model, torch.zeros(1, N_FEATURES), str(models_dir / "symbol_mlp.onnx"), input_names=["features"], output_names=["logits"], dynamic_axes={"features": {0: "n"}, "logits": {0: "n"}}, dynamo=False)
    except Exception as e:  # ONNX is a convenience copy; the .bin is what ships.
        print(f"ONNX export skipped: {e}")

    # Symbol error rates are what matter for Reed-Solomon.
    ser_c, ser_m = 1 - classic_val, 1 - best
    report = {
        "train_symbols": int(len(ytr)),
        "val_symbols": int(len(yva)),
        "classic_val_accuracy": classic_val,
        "ml_val_accuracy": best,
        "symbol_error_rate_classic": ser_c,
        "symbol_error_rate_ml": ser_m,
        "error_reduction": (ser_c - ser_m) / ser_c if ser_c > 0 else 0.0,
        "params": int(sum(p.numel() for p in model.parameters())),
        "bin_bytes": out_bin.stat().st_size,
    }
    (models_dir / "report.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
